(() => {
  const successExample = document.querySelector(".example:first-child");
  const failExample = document.querySelector(".example:last-child");
  const successButton = document.querySelector("#successButton");
  const failButton = document.querySelector("#failButton");
  const successStatus = document.querySelector("#successStatus");
  const failStatus = document.querySelector("#failStatus");
  const message = document.querySelector("#message");
  const resetButton = document.querySelector("#resetButton");
  let timers = [];

  function clearTimers() {
    timers.forEach(clearTimeout);
    timers = [];
  }
  function schedule(fn, delay) {
    timers.push(setTimeout(fn, delay));
  }
  function reset() {
    clearTimers();
    [successExample, failExample].forEach(el => el.classList.remove("loading","done","failed","shake"));
    successStatus.textContent = "SUCCESS";
    failStatus.textContent = "FAIL";
    successStatus.className = "status success-text";
    failStatus.className = "status fail-text";
    message.textContent = "Choose a button to preview its animation.";
  }
  function createDemoFile() {
    const content = "Download button animation demo\\nThis file was generated by the success button.";
    const blob = new Blob([content], {type:"text/plain"});
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "download-success-demo.txt";
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1500);
  }
  successButton.addEventListener("click", () => {
    reset();
    successExample.classList.add("loading");
    successStatus.textContent = "DOWNLOADING";
    message.textContent = "Preparing your file…";
    schedule(() => {
      successExample.classList.remove("loading");
      successExample.classList.add("done");
      successStatus.textContent = "SUCCESS";
      successStatus.className = "status live-success";
      message.textContent = "Download complete — demo file saved.";
      createDemoFile();
    }, 1050);
  });
  failButton.addEventListener("click", () => {
    reset();
    failExample.classList.add("loading");
    failStatus.textContent = "CONNECTING";
    message.textContent = "Attempting a simulated download…";
    schedule(() => {
      failExample.classList.remove("loading");
      failExample.classList.add("failed","shake");
      failStatus.textContent = "FAILED";
      failStatus.className = "status live-fail";
      message.textContent = "Download failed — this is a simulated error state.";
    }, 1050);
  });
  resetButton.addEventListener("click", reset);
})();